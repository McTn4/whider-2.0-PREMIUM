def f(v):
    s = ('%.2f' % v).rstrip('0').rstrip('.')
    return s if s not in ('-0', '') else '0'

def R(x, y, w, h, r=None):
    """Rectángulo de esquinas curvadas (el rasgo de la colección). Si el icono no fija el radio,
    crece con la forma: 2,75 en los contenedores grandes, 2,2 en los apaisados, 1,6 en los medianos
    y 1 en los pequeños (para que sigan leyéndose como cuadrados y no como círculos)."""
    m = min(w, h)
    if r is None:
        r = 2.75 if m >= 15 else 2.2 if m >= 11 else 1.6 if m >= 8 else 1.0
    r = min(r, m / 2)
    a = 'A%s %s 0 0 1 ' % (f(r), f(r))
    return 'M%s %sH%s%s%s %sV%s%s%s %sH%s%s%s %sV%s%s%s %sZ' % (
        f(x + r), f(y), f(x + w - r), a, f(x + w), f(y + r), f(y + h - r), a, f(x + w - r), f(y + h),
        f(x + r), a, f(x), f(y + h - r), f(y + r), a, f(x + r), f(y))
