def rays(cx, cy, r1, r2, n=8, start=-90):
    out = []
    for i in range(n):
        x1, y1 = polar(cx, cy, r1, start + i * 360 / n); x2, y2 = polar(cx, cy, r2, start + i * 360 / n)
        out.append('M%s %sL%s %s' % (f(x1), f(y1), f(x2), f(y2)))
    return P(''.join(out))

