INICIO = '<svg width="0" height="0" style="position:absolute" aria-hidden="true">'


def escribir(ruta):
    """Sustituye el sprite de iconos dentro de index.html por el que genera este archivo."""
    html = open(ruta, encoding='utf-8').read()
    a = html.find(INICIO)
    if a < 0:
        sys.exit('No encuentro el sprite de iconos en ' + ruta)
    b = html.find('</svg>', a) + len('</svg>')
    nuevo = html[:a] + sprite() + html[b:]
    if nuevo == html:
        print('index.html ya tenía estos iconos: sin cambios')
        return
    open(ruta, 'w', encoding='utf-8').write(nuevo)
    print('Iconos actualizados en', ruta)


